"use client";

import { Printer } from "lucide-react";
import { PROXY_PREFIX } from "@/lib/api/client";
import type { AssetDetailsDto } from "@/lib/api/types";
import { categoryLabel } from "@/lib/assets";
import { Button } from "@/components/ui/button";
import { PageHeader } from "@/components/ui/page-header";

/** Printable labels (≈ 70 × 37 mm each): name, tag barcode and QR code. Print hides the app chrome. */
export function LabelSheet({ assets, companyName }: { assets: AssetDetailsDto[]; companyName: string }) {
  return (
    <>
      <style>{`@media print {
  body * { visibility: hidden; }
  #label-sheet, #label-sheet * { visibility: visible; }
  #label-sheet { position: absolute; inset: 0; padding: 0; }
  .label { break-inside: avoid; border-color: #000 !important; }
  @page { margin: 8mm; }
}`}</style>
      <div className="print:hidden">
        <PageHeader
          title={`Asset labels (${assets.length})`}
          description="Prints one label per asset. Use a label printer or adhesive A4 label sheets."
          actions={
            <Button onClick={() => window.print()}>
              <Printer className="h-4 w-4" /> Print
            </Button>
          }
        />
      </div>
      <div id="label-sheet" className="grid grid-cols-1 gap-3 sm:grid-cols-2 lg:grid-cols-3 print:grid-cols-3 print:gap-2">
        {assets.map((a) => (
          <div key={a.summary.id} className="label flex items-center gap-3 rounded-md border border-border bg-white p-3 text-black">
            <div className="min-w-0 flex-1">
              <p className="truncate text-[10px] uppercase tracking-wide text-neutral-600">{companyName}</p>
              <p className="truncate text-sm font-semibold">{a.summary.name}</p>
              <p className="truncate text-[11px] text-neutral-600">
                {categoryLabel(a.summary.category)}
                {a.summary.serialNumber ? ` · SN ${a.summary.serialNumber}` : ""}
              </p>
              {/* eslint-disable-next-line @next/next/no-img-element -- SVG generated by the API */}
              <img src={`${PROXY_PREFIX}/assets/${a.summary.id}/barcode.svg`} alt={`Barcode ${a.summary.assetTag}`} className="mt-1 h-14 w-full object-contain object-left" />
            </div>
            {/* eslint-disable-next-line @next/next/no-img-element -- SVG generated by the API */}
            <img src={`${PROXY_PREFIX}/assets/${a.summary.id}/qr.svg`} alt={`QR code ${a.summary.assetTag}`} className="h-20 w-20 shrink-0" />
          </div>
        ))}
      </div>
    </>
  );
}
