public sealed record ReportDto(
    Guid Id,
    string Title,
    ReportKind Kind,
    string ContentMarkdown,
    bool NarrativeIncluded,
    string? Model,
    string? GeneratedByEmail,
    DateTimeOffset CreatedAtUtc);

public sealed record ReportSummaryDto(Guid Id, string Title, ReportKind Kind, bool NarrativeIncluded, string? GeneratedByEmail, DateTimeOffset CreatedAtUtc);

public sealed record GenerateReportRequest(ReportKind Kind, Guid? BranchId, IReadOnlyList<Guid>? DepartmentIds, string? Title);

public interface IReportService
{
    Task<ReportDto> GenerateAsync(GenerateReportRequest request, Guid? conversationId, CancellationToken cancellationToken);

    Task<PagedResult<ReportSummaryDto>> ListAsync(PageRequest page, CancellationToken cancellationToken);

    Task<ReportDto> GetAsync(Guid id, CancellationToken cancellationToken);

    Task DeleteAsync(Guid id, CancellationToken cancellationToken);
}

/// <summary>
/// Reports are assembled in two layers: the data tables are produced deterministically from the
/// authorised fleet services; the model only writes the executive summary from those same facts.
/// If the model is unavailable the report is still produced, without the narrative.
/// </summary>
internal sealed partial class ReportService(
    ISolvixDbContext db,
    IAssistantPrincipalAccessor principals,
    IFleetQueryService fleet,
    IChatModel model,
    IAssistantAuditLog audit,
    IClock clock,
    Microsoft.Extensions.Options.IOptions<Configuration.AssistantOptions> options,
    ILogger<ReportService> logger) : IReportService
{
    private const string NarrativeSystemPrompt =
        "You are an IT operations analyst writing for a company's IT administrators. From the FACTS provided, write: " +
        "1) a 3-5 sentence executive summary, 2) 3-6 prioritised recommendations as a numbered list. " +
        "Use only the facts given; do not invent numbers, devices or causes. Do not include commands or scripts. Plain markdown, no headings above level 3.";

    private static readonly JsonSerializerOptions Json = new(JsonSerializerDefaults.Web);

    public async Task<ReportDto> GenerateAsync(GenerateReportRequest request, Guid? conversationId, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(request);
        var principal = principals.Current;
        if (!fleet.IsAvailable)
        {
            throw new ServiceUnavailableException("No fleet data source is connected, so reports cannot be generated.", "fleet_unavailable");
        }

        var access = principal.ToFleetAccess();
        var scope = new FleetScope(request.BranchId, request.DepartmentIds);
        var facts = await BuildFactsAsync(request.Kind, access, scope, cancellationToken);
        facts = SecretRedactor.RedactText(facts);

        string? narrative = null;
        if (model.IsConfigured)
        {
            try
            {
                var response = await model.CompleteAsync(
                    new ChatRequest(NarrativeSystemPrompt, [ChatMessage.User("FACTS:\n\n" + facts)], [], options.Value.Llm.MaxOutputTokens),
                    cancellationToken);
                narrative = SecretRedactor.RedactText(response.Text).Trim();
            }
            catch (ChatModelException ex)
            {
                LogNarrativeFailed(logger, ex.Message);
            }
        }

        var title = string.IsNullOrWhiteSpace(request.Title)
            ? $"{Humanize(request.Kind)} report – {clock.UtcNow:yyyy-MM-dd}"
            : SecretRedactor.RedactText(request.Title).Trim();
        var sb = new StringBuilder()
            .Append("# ").AppendLine(title)
            .AppendLine()
            .AppendLine(CultureInfo.InvariantCulture, $"_Generated {clock.UtcNow:yyyy-MM-dd HH:mm} UTC by {principal.Email}._")
            .AppendLine();
        if (!string.IsNullOrEmpty(narrative))
        {
            sb.AppendLine("## Summary and recommendations (AI-generated)").AppendLine().AppendLine(narrative).AppendLine();
        }

        sb.AppendLine("## Data (generated by the platform)").AppendLine().Append(facts);

        var report = new AssistantReport(
            principal.TenantId,
            title.Length > AssistantReport.TitleMaxLength ? title[..AssistantReport.TitleMaxLength] : title,
            request.Kind,
            sb.ToString(),
            JsonSerializer.Serialize(new { request.Kind, request.BranchId, request.DepartmentIds }, Json),
            !string.IsNullOrEmpty(narrative),
            string.IsNullOrEmpty(narrative) ? null : model.ModelName,
            principal.UserId,
            principal.Email,
            conversationId);
        db.Set<AssistantReport>().Add(report);
        await db.SaveChangesAsync(cancellationToken);
        await audit.RecordAsync(new AuditRecord(AuditKinds.ReportGenerated, request.Kind.ToString(), AuditStatus.Success, conversationId, Summary: report.Title, Model: report.Model), cancellationToken);
        return ToDto(report);
    }

    public async Task<PagedResult<ReportSummaryDto>> ListAsync(PageRequest page, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(page);
        var query = db.Set<AssistantReport>().AsNoTracking();
        var total = await query.LongCountAsync(cancellationToken);
        var items = await query.OrderByDescending(r => r.Id).Skip(page.Skip).Take(page.SafePageSize)
            .Select(r => new ReportSummaryDto(r.Id, r.Title, r.Kind, r.NarrativeIncluded, r.GeneratedByEmail, r.CreatedAtUtc))
            .ToListAsync(cancellationToken);
        return new PagedResult<ReportSummaryDto>(items, page.SafePage, page.SafePageSize, total);
    }

    public async Task<ReportDto> GetAsync(Guid id, CancellationToken cancellationToken) =>
        ToDto(await db.Set<AssistantReport>().AsNoTracking().FirstOrDefaultAsync(r => r.Id == id, cancellationToken)
            ?? throw new NotFoundException("Report", id));

    public async Task DeleteAsync(Guid id, CancellationToken cancellationToken)
    {
        if (!principals.Current.HasAtLeast(Solvix.SharedKernel.Identity.TenantRole.Admin))
        {
            throw new ForbiddenException("Deleting reports requires the Admin or Owner role.");
        }

        var report = await db.Set<AssistantReport>().FirstOrDefaultAsync(r => r.Id == id, cancellationToken)
            ?? throw new NotFoundException("Report", id);
        db.Set<AssistantReport>().Remove(report);
        await db.SaveChangesAsync(cancellationToken);
    }

    private async Task<string> BuildFactsAsync(ReportKind kind, FleetAccess access, FleetScope scope, CancellationToken ct)
    {
        var sb = new StringBuilder();
        switch (kind)
        {
            case ReportKind.FleetHealth:
                await FleetHealthAsync(sb, access, scope, ct);
                break;
            case ReportKind.SoftwareInventory:
                await SoftwareAsync(sb, access, scope, ct);
                break;
            case ReportKind.Security:
                await SecurityAsync(sb, access, scope, ct);
                break;
            case ReportKind.Performance:
                await PerformanceAsync(sb, access, scope, ct);
                break;
            default:
                throw new ValidationException("kind", "Unsupported report kind.");
        }

        return sb.ToString();
    }

    private async Task FleetHealthAsync(StringBuilder sb, FleetAccess access, FleetScope scope, CancellationToken ct)
    {
        var s = await fleet.GetSummaryAsync(access, scope, ct);
        sb.AppendLine("### Fleet status").AppendLine()
            .AppendLine(CultureInfo.InvariantCulture, $"- Total devices: {s.Total}")
            .AppendLine(CultureInfo.InvariantCulture, $"- Online: {s.Online}")
            .AppendLine(CultureInfo.InvariantCulture, $"- Offline: {s.Offline}")
            .AppendLine(CultureInfo.InvariantCulture, $"- Unknown: {s.Unknown}")
            .AppendLine(CultureInfo.InvariantCulture, $"- Low free storage (<10 GB): {s.LowStorage}").AppendLine();
        if (s.ByOperatingSystem.Count > 0)
        {
            sb.AppendLine("### Operating systems").AppendLine().AppendLine("| OS | Devices |").AppendLine("|---|---|");
            foreach (var (os, count) in s.ByOperatingSystem.OrderByDescending(k => k.Value))
            {
                sb.AppendLine(CultureInfo.InvariantCulture, $"| {Cell(os)} | {count} |");
            }

            sb.AppendLine();
        }

        if (s.ByBranch.Count > 0)
        {
            sb.AppendLine("### By branch").AppendLine().AppendLine("| Branch | Total | Online | Offline |").AppendLine("|---|---|---|---|");
            foreach (var b in s.ByBranch)
            {
                sb.AppendLine(CultureInfo.InvariantCulture, $"| {Cell(b.BranchName)} | {b.Total} | {b.Online} | {b.Offline} |");
            }

            sb.AppendLine();
        }

        var (offline, _) = await fleet.SearchAsync(access, new DeviceSearchCriteria { Status = DeviceConnectivity.Offline, BranchId = scope.BranchId, DepartmentIds = scope.DepartmentIds, Sort = DeviceSort.LastSeen }, 0, 15, ct);
        DeviceTable(sb, "Offline devices (up to 15)", offline);
        var (lowDisk, _) = await fleet.SearchAsync(access, new DeviceSearchCriteria { MaxFreeStorageBytes = 10L * 1024 * 1024 * 1024, BranchId = scope.BranchId, DepartmentIds = scope.DepartmentIds, Sort = DeviceSort.FreeStorageAsc }, 0, 15, ct);
        DeviceTable(sb, "Lowest free storage (up to 15)", lowDisk);
    }

    private async Task PerformanceAsync(StringBuilder sb, FleetAccess access, FleetScope scope, CancellationToken ct)
    {
        var (cpu, _) = await fleet.SearchAsync(access, new DeviceSearchCriteria { BranchId = scope.BranchId, DepartmentIds = scope.DepartmentIds, Sort = DeviceSort.CpuUsageDesc, Status = DeviceConnectivity.Online }, 0, 10, ct);
        DeviceTable(sb, "Highest CPU usage (top 10)", cpu);
        var (mem, _) = await fleet.SearchAsync(access, new DeviceSearchCriteria { BranchId = scope.BranchId, DepartmentIds = scope.DepartmentIds, Sort = DeviceSort.MemoryUsageDesc, Status = DeviceConnectivity.Online }, 0, 10, ct);
        DeviceTable(sb, "Highest memory usage (top 10)", mem);
    }

    private async Task SoftwareAsync(StringBuilder sb, FleetAccess access, FleetScope scope, CancellationToken ct)
    {
        var outdated = await fleet.FindSoftwareAsync(access, new SoftwareSearchCriteria(null, null, true, scope), 25, ct);
        sb.AppendLine("### Outdated software (top 25 by device count)").AppendLine();
        if (outdated.Count == 0)
        {
            sb.AppendLine("No outdated software detected.").AppendLine();
        }
        else
        {
            sb.AppendLine("| Software | Installed | Latest | Devices | Examples |").AppendLine("|---|---|---|---|---|");
            foreach (var e in outdated)
            {
                sb.AppendLine(CultureInfo.InvariantCulture, $"| {Cell(e.Name)} | {Cell(e.Version)} | {Cell(e.LatestVersion ?? "?")} | {e.DeviceCount} | {Cell(string.Join(", ", e.ExampleDevices))} |");
            }

            sb.AppendLine();
        }

        var all = await fleet.FindSoftwareAsync(access, new SoftwareSearchCriteria(null, null, false, scope), 25, ct);
        sb.AppendLine("### Most widely installed software (top 25)").AppendLine().AppendLine("| Software | Version | Devices |").AppendLine("|---|---|---|");
        foreach (var e in all)
        {
            sb.AppendLine(CultureInfo.InvariantCulture, $"| {Cell(e.Name)} | {Cell(e.Version)} | {e.DeviceCount} |");
        }

        sb.AppendLine();
    }

    private async Task SecurityAsync(StringBuilder sb, FleetAccess access, FleetScope scope, CancellationToken ct)
    {
        var advice = SecurityAdvisor.Advise(await fleet.GetSecurityPostureAsync(access, scope, ct), 25);
        sb.AppendLine(CultureInfo.InvariantCulture, $"### Security posture ({advice.TotalDevices} devices)").AppendLine();
        foreach (var (kind, count) in advice.CountsByKind)
        {
            sb.AppendLine(CultureInfo.InvariantCulture, $"- {kind}: {count}");
        }

        sb.AppendLine().AppendLine("### Platform recommendations").AppendLine();
        foreach (var r in advice.Recommendations)
        {
            sb.AppendLine(CultureInfo.InvariantCulture, $"- {r}");
        }

        sb.AppendLine().AppendLine("### Highest-severity findings").AppendLine().AppendLine("| Device | Finding | Severity | Detail |").AppendLine("|---|---|---|---|");
        foreach (var f in advice.TopFindings)
        {
            sb.AppendLine(CultureInfo.InvariantCulture, $"| {Cell(f.DeviceName)} | {f.Kind} | {f.Severity} | {Cell(f.Detail)} |");
        }

        sb.AppendLine();
    }

    private static void DeviceTable(StringBuilder sb, string heading, IReadOnlyList<DeviceSummary> devices)
    {
        sb.AppendLine(CultureInfo.InvariantCulture, $"### {heading}").AppendLine();
        if (devices.Count == 0)
        {
            sb.AppendLine("None.").AppendLine();
            return;
        }

        sb.AppendLine("| Device | Branch | Status | CPU % | Mem % | Free GB | Last seen (UTC) |").AppendLine("|---|---|---|---|---|---|---|");
        foreach (var d in devices)
        {
            sb.AppendLine(CultureInfo.InvariantCulture,
                $"| {Cell(d.Name)} | {Cell(d.BranchName ?? "-")} | {d.Status} | {d.CpuUsagePercent?.ToString("0", CultureInfo.InvariantCulture) ?? "-"} | {d.MemoryUsagePercent?.ToString("0", CultureInfo.InvariantCulture) ?? "-"} | {(d.FreeStorageBytes is { } f ? (f / 1_073_741_824.0).ToString("0.#", CultureInfo.InvariantCulture) : "-")} | {d.LastSeenUtc?.ToString("yyyy-MM-dd HH:mm", CultureInfo.InvariantCulture) ?? "-"} |");
        }

        sb.AppendLine();
    }

    private static string Cell(string value) => value.Replace("|", "\\|", StringComparison.Ordinal).Replace("\n", " ", StringComparison.Ordinal);

    private static string Humanize(ReportKind kind) => kind switch
    {
        ReportKind.FleetHealth => "Fleet health",
        ReportKind.SoftwareInventory => "Software inventory",
        ReportKind.Security => "Security posture",
        ReportKind.Performance => "Performance",
        _ => kind.ToString(),
    };

    private static ReportDto ToDto(AssistantReport r) => new(r.Id, r.Title, r.Kind, r.ContentMarkdown, r.NarrativeIncluded, r.Model, r.GeneratedByEmail, r.CreatedAtUtc);

    [LoggerMessage(Level = LogLevel.Warning, Message = "Report narrative could not be generated: {Reason}")]
    private static partial void LogNarrativeFailed(ILogger logger, string reason);
}
