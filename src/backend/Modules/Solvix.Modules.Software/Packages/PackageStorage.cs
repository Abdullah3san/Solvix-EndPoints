namespace Solvix.Modules.Software.Packages;

using System.Security.Cryptography;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;
using Solvix.Modules.Software.Configuration;

/// <summary>
/// Where package files live. Files are addressed by tenant and opaque key only — never by an
/// uploaded name — and are only ever read as bytes. A cloud object store can replace
/// <see cref="FileSystemPackageStorage"/> behind this interface.
/// </summary>
public interface IPackageStorage
{
    /// <summary>A private temporary file for an upload in progress (deleted by the caller).</summary>
    string CreateTemporaryPath();

    /// <summary>Moves a validated temporary file into the store (atomic; never overwrites).</summary>
    Task CommitAsync(Guid tenantId, string storageKey, string temporaryPath, CancellationToken cancellationToken);

    /// <summary>Opens a stored package for reading, or null when it is missing.</summary>
    Stream? OpenRead(Guid tenantId, string storageKey);

    /// <summary>Path of a stored package for range-capable serving, or null when missing.</summary>
    string? Locate(Guid tenantId, string storageKey);

    Task<(string Sha256, long Length)?> HashAsync(Guid tenantId, string storageKey, CancellationToken cancellationToken);

    void Delete(Guid tenantId, string storageKey);
}

public sealed partial class FileSystemPackageStorage : IPackageStorage
{
    private readonly string _root;
    private readonly ILogger<FileSystemPackageStorage> _logger;

    public FileSystemPackageStorage(IOptions<SoftwareOptions> options, ILogger<FileSystemPackageStorage> logger)
    {
        ArgumentNullException.ThrowIfNull(options);
        _logger = logger;
        _root = Path.GetFullPath(options.Value.Storage.RootPath);
        CreatePrivateDirectory(_root);
        CreatePrivateDirectory(Path.Combine(_root, "incoming"));
    }

    public string CreateTemporaryPath() => Path.Combine(_root, "incoming", Guid.NewGuid().ToString("N") + ".part");

    public async Task CommitAsync(Guid tenantId, string storageKey, string temporaryPath, CancellationToken cancellationToken)
    {
        var target = PathOf(tenantId, storageKey);
        CreatePrivateDirectory(Path.GetDirectoryName(target)!);
        File.Move(temporaryPath, target, overwrite: false);
        if (!OperatingSystem.IsWindows())
        {
            File.SetUnixFileMode(target, UnixFileMode.UserRead | UnixFileMode.UserWrite);
        }

        LogStored(_logger, tenantId, storageKey);
        await Task.CompletedTask;
    }

    public Stream? OpenRead(Guid tenantId, string storageKey)
    {
        var path = PathOf(tenantId, storageKey);
        return File.Exists(path) ? new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read, 81920, FileOptions.Asynchronous | FileOptions.SequentialScan) : null;
    }

    public string? Locate(Guid tenantId, string storageKey)
    {
        var path = PathOf(tenantId, storageKey);
        return File.Exists(path) ? path : null;
    }

    public async Task<(string Sha256, long Length)?> HashAsync(Guid tenantId, string storageKey, CancellationToken cancellationToken)
    {
        await using var stream = OpenRead(tenantId, storageKey);
        if (stream is null)
        {
            return null;
        }

        var hash = await SHA256.HashDataAsync(stream, cancellationToken);
        return (Convert.ToHexStringLower(hash), stream.Length);
    }

    public void Delete(Guid tenantId, string storageKey)
    {
        var path = PathOf(tenantId, storageKey);
        if (File.Exists(path))
        {
            File.Delete(path);
        }
    }

    private string PathOf(Guid tenantId, string storageKey)
    {
        // Keys are generated by the server (Guid "N"); anything else is a programming error.
        if (storageKey.Length != 32 || !storageKey.All(char.IsAsciiHexDigitLower))
        {
            throw new ArgumentException("Invalid storage key.", nameof(storageKey));
        }

        return Path.Combine(_root, tenantId.ToString("N"), storageKey + ".pkg");
    }

    private static void CreatePrivateDirectory(string path)
    {
        if (OperatingSystem.IsWindows())
        {
            Directory.CreateDirectory(path);
        }
        else
        {
            Directory.CreateDirectory(path, UnixFileMode.UserRead | UnixFileMode.UserWrite | UnixFileMode.UserExecute);
        }
    }

    [LoggerMessage(Level = LogLevel.Information, Message = "Stored package {StorageKey} for tenant {TenantId}")]
    private static partial void LogStored(ILogger logger, Guid tenantId, string storageKey);
}
