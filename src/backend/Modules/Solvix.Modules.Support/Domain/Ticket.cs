namespace Solvix.Modules.Support.Domain;

using Solvix.Agent.Contracts;
using Solvix.SharedKernel.Entities;
using Solvix.SharedKernel.Exceptions;
using Solvix.SharedKernel.Guards;

public enum TicketSource
{
    Agent = 1,
    Web = 2,
}

/// <summary>A support request, raised from a laptop through the agent or from the web console.</summary>
public sealed class Ticket : TenantEntity
{
    public const int SubjectMaxLength = SubmitTicketRequest.SubjectMaxLength;
    public const int DescriptionMaxLength = SubmitTicketRequest.DescriptionMaxLength;
    public const int RequesterMaxLength = 200;

    private Ticket()
    {
    }

    /// <summary>Human-friendly number, generated by the database.</summary>
    public long Number { get; private set; }

    public Guid? DeviceId { get; private set; }

    public string Subject { get; private set; } = string.Empty;

    public string? Description { get; private set; }

    public TicketStatus Status { get; private set; } = TicketStatus.Open;

    public TicketPriority Priority { get; private set; } = TicketPriority.Normal;

    public TicketSource Source { get; private set; }

    public string? RequesterName { get; private set; }

    public string? RequesterEmail { get; private set; }

    public Guid? AssignedUserId { get; private set; }

    public DateTimeOffset? ResolvedAtUtc { get; private set; }

    public static Ticket Create(
        Guid tenantId,
        TicketSource source,
        Guid? deviceId,
        string subject,
        string? description,
        TicketPriority priority,
        string? requesterName,
        string? requesterEmail)
    {
        if (!Enum.IsDefined(priority))
        {
            throw new ValidationException("priority", "Unknown priority.");
        }

        var ticket = new Ticket
        {
            Source = source,
            DeviceId = deviceId,
            Subject = Guard.NotNullOrWhiteSpace(subject, "subject", SubjectMaxLength),
            Description = Guard.Optional(description, "description", DescriptionMaxLength),
            Priority = priority,
            RequesterName = Guard.Optional(requesterName, "requesterName", RequesterMaxLength),
            RequesterEmail = Guard.Optional(requesterEmail, "requesterEmail", RequesterMaxLength),
        };
        ticket.AssignTenant(tenantId);
        return ticket;
    }

    public void ChangeStatus(TicketStatus status, DateTimeOffset now)
    {
        if (!Enum.IsDefined(status))
        {
            throw new ValidationException("status", "Unknown status.");
        }

        if (status is TicketStatus.Resolved or TicketStatus.Closed)
        {
            ResolvedAtUtc ??= now;
        }
        else
        {
            ResolvedAtUtc = null;
        }

        Status = status;
    }

    public void ChangePriority(TicketPriority priority)
    {
        if (!Enum.IsDefined(priority))
        {
            throw new ValidationException("priority", "Unknown priority.");
        }

        Priority = priority;
    }

    public void Assign(Guid? userId) => AssignedUserId = userId;

    /// <summary>A reply from the requester re-opens a ticket that was waiting to be closed.</summary>
    public void ReopenIfResolved(DateTimeOffset now)
    {
        if (Status == TicketStatus.Resolved)
        {
            ChangeStatus(TicketStatus.Open, now);
        }
    }
}

public enum CommentAuthor
{
    Requester = 1,
    Technician = 2,
}

public sealed class TicketComment : TenantEntity
{
    public const int AuthorNameMaxLength = 200;

    private TicketComment()
    {
    }

    public Guid TicketId { get; private set; }

    public CommentAuthor Author { get; private set; }

    public Guid? AuthorUserId { get; private set; }

    public string? AuthorName { get; private set; }

    public string Body { get; private set; } = string.Empty;

    /// <summary>Technician-only note; never sent to the agent.</summary>
    public bool IsInternal { get; private set; }

    public static TicketComment Create(Guid tenantId, Guid ticketId, CommentAuthor author, Guid? authorUserId, string? authorName, string body, bool isInternal)
    {
        var comment = new TicketComment
        {
            TicketId = ticketId,
            Author = author,
            AuthorUserId = authorUserId,
            AuthorName = Guard.Optional(authorName, "authorName", AuthorNameMaxLength),
            Body = Guard.NotNullOrWhiteSpace(body, "body", Ticket.DescriptionMaxLength),
            IsInternal = isInternal && author == CommentAuthor.Technician,
        };
        comment.AssignTenant(tenantId);
        return comment;
    }
}

/// <summary>One line of the live conversation between a technician and the person using a device.</summary>
public sealed class DeviceChatMessage : TenantEntity
{
    private DeviceChatMessage()
    {
    }

    /// <summary>Global, strictly increasing position (database identity); clients page by it.</summary>
    public long Sequence { get; private set; }

    public Guid DeviceId { get; private set; }

    public ChatSender Sender { get; private set; }

    public Guid? SenderUserId { get; private set; }

    public string? SenderName { get; private set; }

    public string Body { get; private set; } = string.Empty;

    public static DeviceChatMessage Create(Guid tenantId, Guid deviceId, ChatSender sender, Guid? senderUserId, string? senderName, string body)
    {
        var message = new DeviceChatMessage
        {
            DeviceId = deviceId,
            Sender = sender,
            SenderUserId = senderUserId,
            SenderName = Guard.Optional(senderName, "senderName", 200),
            Body = Guard.NotNullOrWhiteSpace(body, "body", ChatMessage.BodyMaxLength),
        };
        message.AssignTenant(tenantId);
        return message;
    }
}
